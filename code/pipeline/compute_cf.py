#!/usr/bin/env python3
"""
Capacity Factor (CF) computation at hourly timestep, regional aggregation,
and diagnostic plots.

Pipeline
--------
0. Validation  — alignment check on training period (ERA5 ref vs raw GCM vs BC GCM),
                 using daily BC files (same as before).
1. Hourly CF   — wind / solar CF from hourly downscaled files
                 (produced by downscale_hourly.py apply/apply_hist).
                 Both historical and SSP hourly files are expected; the
                 historical hourly file is generated by passing
                 ``--scenarios historical`` to downscale_hourly.py apply.
2. Aggregation — annual mean CF per Indian state from hourly CF grids.
3. Plots       — time-series per state + 20-year gridded maps.
                 An extra "hourly validation" panel compares the diurnal
                 cycle of solar CF between ERA5-derived hourly and BC hourly
                 on the training period.

Hourly solar CF
---------------
With hourly data the instantaneous cell temperature formula is applied
directly to hourly rsds, tas and sfcWind.  Because tasmax is not available
at hourly resolution the hourly tas is used in its place (conservative;
see note in solar_cf_hourly).

Hourly wind CF
--------------
10 m wind is extrapolated to hub height (default 150 m) with a per-pixel
Hellmann shear exponent fit on ERA5 u10/v10/u100/v100 over 1982-2001
(--shear-file; --wind-method shear_uniform uses a single 1/7 instead), then
passed through the turbine power curve.

Regional aggregation (identical for wCF and sCF)
------------------------------------------------
State means are written three ways: area-weighted over the state polygons,
area-weighted over the polygons buffered by --buffer-km, and weighted by
operating capacity per pixel from the GEM Global Wind / Solar Power Trackers
(--wind-capacity-file / --solar-capacity-file).  A small capacity jitter
(--capacity-jitter MW per pixel, scaled by its area inside the state) is added
to the capacity weights so states without operating capacity fall back to an
area-weighted mean instead of NaN.

Input conventions
-----------------
Hourly files follow the naming convention produced by downscale_hourly.py:
    <gcm>_<scenario>_hourly.nc        (e.g. CanESM5_ssp245_hourly.nc)
    <gcm>_historical_hourly.nc
Each contains variables: rsds (W m-2), tas (K), sfcWind (m s-1).

Daily BC files (for validation) keep the original convention:
    {vname}_{gcm}_{scenario}_bc.nc

Outputs in <out-dir>
--------------------
    validate_{var}_{gcm}.png
    validate_summary_{gcm}.png
    hourly_diurnal_validation_{gcm}.png   (solar CF diurnal cycle)
    {w,s}CF_{gcm}_{scenario}_hourly.nc    (hourly CF grids, all scenarios)
    {w,s}CF_{gcm}_{scenario}_states_annual.csv
    {w,s}CF_{gcm}_{scenario}_states_buffer{km}km_annual.csv   (if --buffer-km > 0)
    wCF_{gcm}_{scenario}_states_capacity_annual.csv   (if --wind-capacity-file)
    sCF_{gcm}_{scenario}_states_capacity_annual.csv   (if --solar-capacity-file)
    {wind,solar}_capacity_projects_used.csv
    timeseries_{w,s}CF_{gcm}.png
    map_{w,s}CF_{gcm}_{ssp}.png

Usage
-----
python compute_cf.py \\
    --bc-dir      /data/proc/cmip6_bc            \\
    --hourly-dir  /data/proc/cmip6_hourly         \\
    --cmip-dir    /data/raw/CanESM5               \\
    --shapefile   /data/INDIA_STATES.geojson       \\
    --out-dir     /data/results/cf                 \\
    --gcm         CanESM5 --run r10i1p1f1          \\
    --ssps        ssp245 ssp585                    \\
    --train-start 1980-01-01                       \\
    --train-end   2010-12-31                       \\
    --region-col  STNAME_SH                        \\
    --shear-file  /data/era5/shear_exponent_local_1982-01-01_2001-12-31.nc \\
    --wind-capacity-file /data/Global-Wind-Power-Tracker-February-2026.xlsx
"""

