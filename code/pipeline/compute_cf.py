# Per-scenario hourly CF writer + aggregation
# ══════════════════════════════════════════════════════════════════════════════

def process_scenario(
    scenario: str,
    hourly_dir: Path,
    out_dir: Path,
    gcm: str,
    run: str,
    gdf,           # None → skip regional aggregation and map plots
    wm,            # xagg weightmap (None when gdf is None)
    region_col: str,
    periods: list,
    is_ssp: bool,
    cfg: CFConfig = CFG,
    alpha: xr.DataArray | None = None,
    wm_buf=None,   # xagg weightmap of the buffered regions (None → skip)
    buffer_km: float = 0.0,
    cap_weights: dict | None = None,   # {"wCF": MW(region, pixel), "sCF": ...}
    aggregate_only: bool = False,      # reuse existing CF NetCDFs, skip maps
    force: bool = False,               # overwrite existing CF NetCDFs
) -> tuple[pd.DataFrame | None, pd.DataFrame | None]:
    """
    Load hourly file for *scenario*, compute hourly wCF and sCF, write NC
    outputs, aggregate to annual-mean per state, and produce map plots for
    SSP scenarios.

    With aggregate_only, the hourly wCF/sCF NetCDFs written by a previous run
    are read back instead, and only the regional aggregation is redone.

    wCF and sCF are aggregated the same way: area-weighted over the state
    polygons, area-weighted over the buffered polygons (if wm_buf), and
    weighted by installed capacity (for each variable present in cap_weights).

    Returns (df_wind_annual, df_solar_annual) or (None, None) on failure.
    """
    log.info("━━━ %s ━━━", scenario)

    if aggregate_only:
        paths = [out_dir / f"{name}_{gcm}_{scenario}_hourly.nc" for name in ("wCF", "sCF")]
        missing = [str(p) for p in paths if not p.exists()]
        if missing:
            log.error("  CF file(s) not found: %s — skipping", ", ".join(missing))
            return None, None
        wCF, sCF = (xr.open_dataset(p, chunks={"time": 24 * 30})[name]
                    for p, name in zip(paths, ("wCF", "sCF")))
        time_idx = pd.DatetimeIndex(wCF.time.values)
    else:
        try:
            ds_h = load_hourly(hourly_dir, gcm, scenario)
        except FileNotFoundError as exc:
            log.error("  %s — skipping", exc)
            return None, None
        time_idx = pd.DatetimeIndex(ds_h.time.values)
        n_lat, n_lon = ds_h.sizes["lat"], ds_h.sizes["lon"]

        # ── Compute CF (lazy) ─────────────────────────────────────────────────
        wCF, sCF = compute_cf_from_hourly_ds(ds_h, cfg, alpha)

    # ── Write hourly CF NetCDFs ───────────────────────────────────────────────
    for cf_da, name in ([] if aggregate_only else [(wCF, "wCF"), (sCF, "sCF")]):
        out_nc = out_dir / f"{name}_{gcm}_{scenario}_hourly.nc"
        if out_nc.exists() and not force:
            log.info("  %s already exists — skipping write", out_nc.name)
        else:
            log.info("  Writing %s …", out_nc.name)
            enc = {
                name: {**ENCODING_HOURLY,
                       "chunksizes": (24, n_lat, n_lon)}
            }
            cf_da.to_netcdf(out_nc, encoding=enc)
            log.info("  → %s", out_nc.name)

    # ── Regional annual aggregation ───────────────────────────────────────────
    log.info("  Aggregating by region …")
    # Load into memory in yearly chunks to keep peak RAM manageable
    cap_weights = cap_weights or {}
    methods = ["area"] + (["buffer"] if wm_buf is not None else [])
    parts = {(v, m): [] for v in ("wCF", "sCF") for m in methods + ["capacity"]}
    years    = sorted(set(time_idx.year))

    for yr in years:
        t_slice = slice(f"{yr}-01-01", f"{yr}-12-31")
        for name, cf_da in [("wCF", wCF), ("sCF", sCF)]:
            cf_yr = cf_da.sel(time=t_slice).load()
            parts[(name, "area")].append(
                regional_annual_mean(cf_yr, wm, gdf, region_col))
            if wm_buf is not None:
                parts[(name, "buffer")].append(
                    regional_annual_mean(cf_yr, wm_buf, gdf, region_col))
            if name in cap_weights:
                parts[(name, "capacity")].append(
                    regional_annual_mean_capacity(cf_yr, cap_weights[name]))
            del cf_yr

    suffix = {"area": "", "buffer": f"_buffer{buffer_km:g}km", "capacity": "_capacity"}
    for (name, method), dfs in parts.items():
        if dfs:
            pd.concat(dfs).to_csv(
                out_dir / f"{name}_{gcm}_{scenario}_states{suffix[method]}_annual.csv")
    df_w = pd.concat(parts[("wCF", "area")])
    df_s = pd.concat(parts[("sCF", "area")])

    # ── 20-year maps (SSP scenarios only) ────────────────────────────────────
    if is_ssp and not aggregate_only:
        log.info("  20-year maps …")
        for cf_da, name, cmap, (vmin, vmax) in [
            (wCF, "wCF", "Blues",   (0.0, 0.50)),
            (sCF, "sCF", "Oranges", (0.0, 0.25)),
        ]:
            cf_20y = {}
            for s, e in periods:
                da_period = cf_da.sel(time=slice(str(s), str(e)))
                # annual mean then period mean  (avoids storing all hourly at once)
                da_ann = da_period.resample(time="YE").mean(skipna=True).mean("time", skipna=True)
                cf_20y[(s, e)] = da_ann.load()
            plot_20y_maps(
                cf_20y, name, gcm, scenario, gdf, cmap, vmin, vmax,
                out_dir / f"map_{name}_{gcm}_{scenario}.png",
            )
            del cf_20y

    if aggregate_only:
        wCF.close()
        sCF.close()
    else:
        ds_h.close()
    return df_w, df_s


