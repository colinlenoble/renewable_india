# ══════════════════════════════════════════════════════════════════════════════
# Main
# ══════════════════════════════════════════════════════════════════════════════

def main():
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    TRAIN = slice(args.train_start, args.train_end)

    # ══════════════════════════════════════════════════════════════════════════
    # 0. Validation — daily BC alignment
    # ══════════════════════════════════════════════════════════════════════════
    if not args.skip_validation:
        log.info("══ Daily BC validation plots ══")
        val_results = {}
        for vname in ["tas", "tasmax", "sfcWind", "rsds"]:
            log.info("  %s", vname)
            try:
                era5 = load_era5_ref(args.bc_dir, vname)
                bc   = load_hist_bc_daily(args.bc_dir, vname, args.gcm)
            except FileNotFoundError as e:
                log.warning("  Skipping %s validation — %s", vname, e)
                continue
            raw = load_hist_raw(args.cmip_dir, vname, args.gcm, args.run, TRAIN)
            if raw is not None:
                raw = raw.assign_coords(lat=era5.lat, lon=era5.lon)
            val_results[vname] = {"era5": era5, "bc": bc, "raw": raw}
            plot_validate_var(
                vname, era5, bc, raw, args.gcm,
                args.out_dir / f"validate_{vname}_{args.gcm}.png",
            )

        if val_results:
            plot_validate_summary(
                val_results, args.gcm,
                args.out_dir / f"validate_summary_{args.gcm}.png",
            )
        del val_results

    # ══════════════════════════════════════════════════════════════════════════
    # 0b. Hourly diurnal validation (solar CF on training period)
    # ══════════════════════════════════════════════════════════════════════════
    log.info("══ Hourly diurnal validation ══")
    plot_diurnal_validation(
        args.hourly_dir, args.gcm,
        args.train_start, args.train_end,
        args.out_dir / f"hourly_diurnal_validation_{args.gcm}.png",
    )

    # ══════════════════════════════════════════════════════════════════════════
    # 1–3. Hourly CF for historical + SSP scenarios
    # ══════════════════════════════════════════════════════════════════════════
    log.info("══ Hourly CF computation ══")
    gdf = gpd.read_file(args.shapefile).to_crs("EPSG:4326")
    log.info("Shapefile: %d regions", len(gdf))

    # Build region mask from the grid of one of the hourly files
    # (try historical first, then first SSP)
    mask_source = hourly_nc_path(args.hourly_dir, args.gcm, "historical")
    if not mask_source.exists():
        mask_source = hourly_nc_path(args.hourly_dir, args.gcm, args.ssps[0])
    with xr.open_dataset(mask_source) as _ds:
        lons, lats = _ds["lon"].values, _ds["lat"].values
    region_mask = build_region_mask(gdf, args.region_col, lons, lats)

    ts_dfs_wind  = {}
    ts_dfs_solar = {}

    # ── Historical hourly CF ──────────────────────────────────────────────────
    df_w_hist, df_s_hist = process_scenario(
        scenario    = "historical",
        hourly_dir  = args.hourly_dir,
        out_dir     = args.out_dir,
        gcm         = args.gcm,
        run         = args.run,
        gdf         = gdf,
        region_mask = region_mask,
        region_col  = args.region_col,
        periods     = PERIODS,
        is_ssp      = False,
    )
    if df_w_hist is not None:
        ts_dfs_wind["historical"]  = df_w_hist
        ts_dfs_solar["historical"] = df_s_hist

    # ── SSP hourly CF ─────────────────────────────────────────────────────────
    for ssp in args.ssps:
        df_w, df_s = process_scenario(
            scenario    = ssp,
            hourly_dir  = args.hourly_dir,
            out_dir     = args.out_dir,
            gcm         = args.gcm,
            run         = args.run,
            gdf         = gdf,
            region_mask = region_mask,
            region_col  = args.region_col,
            periods     = PERIODS,
            is_ssp      = True,
        )
        if df_w is not None:
            ts_dfs_wind[ssp]  = df_w
            ts_dfs_solar[ssp] = df_s

    # ── Combined time-series plots ────────────────────────────────────────────
    if ts_dfs_wind:
        log.info("══ Time-series plots ══")
        plot_timeseries(
            ts_dfs_wind,  "wCF", args.gcm,
            args.out_dir / f"timeseries_wCF_{args.gcm}.png",
        )
        plot_timeseries(
            ts_dfs_solar, "sCF", args.gcm,
            args.out_dir / f"timeseries_sCF_{args.gcm}.png",
        )

    log.info("Done.")


if __name__ == "__main__":
    main()