def hourly_nc_path(hourly_dir: Path, gcm: str, scenario: str) -> Path:
    """
    Return the path of the hourly NetCDF for a given GCM and scenario.
    Convention: <gcm>_<scenario>_hourly.nc
    """
    return hourly_dir / f"{gcm}_{scenario}_hourly.nc"


def load_hourly(hourly_dir: Path, gcm: str, scenario: str) -> xr.Dataset:
    """
    Open hourly downscaled dataset (rsds, tas, sfcWind).
    Uses Dask chunks of 24 h so the time dimension is never fully loaded.
    """
    path = hourly_nc_path(hourly_dir, gcm, scenario)
    if not path.exists():
        raise FileNotFoundError(
            f"Hourly file not found: {path}\n"
            "Run downscale_hourly.py apply (with --scenarios including this scenario) first."
        )
    return xr.open_dataset(path, chunks={"time": 24 * 30})  # ~1 month chunks


# ══════════════════════════════════════════════════════════════════════════════
# CF formulas — hourly versions
# ══════════════════════════════════════════════════════════════════════════════

def wind_cf_hourly(sfcWind: xr.DataArray, cfg: CFConfig = CFG) -> xr.DataArray:
    """
    Instantaneous wind CF from hourly sfcWind.
    Power-law extrapolation from ref_height to hub_height, then piecewise
    cubic / constant turbine power curve.
    """
    w = sfcWind * (cfg.hub_height / cfg.ref_height) ** cfg.alpha
    cf = xr.where(w < cfg.vci,  0.0,
         xr.where(w >= cfg.vco, 0.0,
         xr.where(w >= cfg.vr,  1.0,
                  (w ** 3 - cfg.vci ** 3) / (cfg.vr ** 3 - cfg.vci ** 3))))
    cf = cf.rename("wCF")
    cf.attrs = {
        "units":        "1",
        "long_name":    "Wind capacity factor (hourly)",
        "hub_height_m": cfg.hub_height,
        "timestep":     "hourly",
    }
    return cf


def solar_cf_hourly(
    tas: xr.DataArray,
    rsds: xr.DataArray,
    sfcWind: xr.DataArray,
    cfg: CFConfig = CFG,
) -> xr.DataArray:
    """
    Instantaneous solar PV CF from hourly inputs.

    At hourly resolution tasmax is unavailable; we use hourly tas directly as
    the ambient temperature for the Faiman cell-temperature model.  This is
    slightly conservative (peak afternoon temperatures are the true maximum)
    but introduces no systematic bias over the diurnal cycle.

    Cell temperature model (Faiman 2008):
        T_cell = c1 + c2*T_amb + c3*G + c4*v_wind

    Power ratio:
        P_R = 1 + gamma*(T_cell - T_ref)

    CF = P_R * G / G_stc  (clipped to [0, 1])
    """
    tas_c  = tas - 273.15                           # K → °C
    T_cell = (cfg.c1
              + cfg.c2 * tas_c
              + cfg.c3 * rsds
              + cfg.c4 * sfcWind)
    P_R = 1.0 + cfg.gamma * (T_cell - cfg.T_ref)
    cf = (P_R * rsds / cfg.G_stc).clip(min=0.0, max=1.0)
    cf = cf.rename("sCF")
    cf.attrs = {
        "units":    "1",
        "long_name": "Solar PV capacity factor (hourly)",
        "timestep": "hourly",
        "note":     "hourly tas used in place of tasmax for cell-T model",
    }
    return cf


# ── Convenience wrappers that operate on a whole hourly Dataset ───────────────

def compute_cf_from_hourly_ds(ds: xr.Dataset, cfg: CFConfig = CFG):
    """
    Compute wCF and sCF DataArrays from an hourly Dataset.
    Returns (wCF, sCF).
    """
    wCF = wind_cf_hourly(ds["sfcWind"], cfg)
    sCF = solar_cf_hourly(ds["tas"], ds["rsds"], ds["sfcWind"], cfg)
    return wCF, sCF


# ══════════════════════════════════════════════════════════════════════════════
# Validation diagnostics (daily-based, unchanged logic)
# ══════════════════════════════════════════════════════════════════════════════

def _domain_mean(da: xr.DataArray) -> xr.DataArray:
    return da.mean(["lat", "lon"], skipna=True)


def _monthly_clim(da: xr.DataArray) -> np.ndarray:
    return _domain_mean(da).groupby("time.month").mean().values


def _annual_ts(da: xr.DataArray) -> tuple[np.ndarray, np.ndarray]:
    dm = _domain_mean(da).resample(time="YE").mean(skipna=True)
    return dm.time.dt.year.values, dm.values


def _kde(da: xr.DataArray, n_pts: int = 300) -> tuple[np.ndarray, np.ndarray]:
    flat = da.values.ravel()
    flat = flat[~np.isnan(flat)]
    if len(flat) > 500_000:
        flat = np.random.default_rng(0).choice(flat, 500_000, replace=False)
    kde = gaussian_kde(flat, bw_method="scott")
    x = np.linspace(np.percentile(flat, 0.5), np.percentile(flat, 99.5), n_pts)
    return x, kde(x)


def plot_validate_var(
    vname: str,
    era5: xr.DataArray,
    bc: xr.DataArray,
    raw: xr.DataArray | None,
    gcm: str,
    out_path: Path,
):
    """4-panel per-variable daily validation figure."""
    months = list("JFMAMJJASOND")
    label  = VAR_LABELS.get(vname, vname)

    fig = plt.figure(figsize=(16, 10))
    fig.suptitle(f"{label}  |  bias-correction alignment — {gcm}", fontsize=12)
    gs = gridspec.GridSpec(2, 3, figure=fig, hspace=0.40, wspace=0.35)
    ax_clim     = fig.add_subplot(gs[0, 0])
    ax_pdf      = fig.add_subplot(gs[0, 1])
    ax_ts       = fig.add_subplot(gs[0, 2])
    ax_bias_raw = fig.add_subplot(gs[1, 0], projection=ccrs.PlateCarree())
    ax_bias_bc  = fig.add_subplot(gs[1, 1], projection=ccrs.PlateCarree())
    ax_cb_space = fig.add_subplot(gs[1, 2])
    ax_cb_space.axis("off")

    log.info("    loading validation data into memory …")
    era5_m = era5.load()
    bc_m   = bc.load()
    raw_m  = raw.load() if raw is not None else None

    # Monthly climatology
    ax_clim.plot(range(1, 13), _monthly_clim(era5_m), "k-o",  ms=4, lw=1.5, label="ERA5 ref")
    ax_clim.plot(range(1, 13), _monthly_clim(bc_m),   "b-s",  ms=4, lw=1.5, label="GCM bc")
    if raw_m is not None:
        ax_clim.plot(range(1, 13), _monthly_clim(raw_m), "r--^", ms=4, lw=1.2, label="GCM raw")
    ax_clim.set_xticks(range(1, 13))
    ax_clim.set_xticklabels(months, fontsize=8)
    ax_clim.set_ylabel(label, fontsize=8)
    ax_clim.set_title("Monthly climatology", fontsize=9)
    ax_clim.legend(fontsize=7)
    ax_clim.grid(True, alpha=0.3)

    # PDF
    xe, ye = _kde(era5_m)
    xb, yb = _kde(bc_m)
    ax_pdf.plot(xe, ye, "k-",  lw=1.5, label="ERA5 ref")
    ax_pdf.plot(xb, yb, "b-",  lw=1.5, label="GCM bc")
    if raw_m is not None:
        xr_, yr = _kde(raw_m)
        ax_pdf.plot(xr_, yr, "r--", lw=1.2, label="GCM raw")
    ax_pdf.set_xlabel(label, fontsize=8)
    ax_pdf.set_ylabel("Density", fontsize=8)
    ax_pdf.set_title("PDF of daily values", fontsize=9)
    ax_pdf.legend(fontsize=7)
    ax_pdf.grid(True, alpha=0.3)

    # Annual time series
    yr_e, ts_e = _annual_ts(era5_m)
    yr_b, ts_b = _annual_ts(bc_m)
    ax_ts.plot(yr_e, ts_e, "k-o", ms=3, lw=1.5, label="ERA5 ref")
    ax_ts.plot(yr_b, ts_b, "b-s", ms=3, lw=1.5, label="GCM bc")
    if raw_m is not None:
        yr_r, ts_r = _annual_ts(raw_m)
        ax_ts.plot(yr_r, ts_r, "r--^", ms=3, lw=1.2, label="GCM raw")
    ax_ts.set_ylabel(label, fontsize=8)
    ax_ts.set_title("Annual mean (domain avg)", fontsize=9)
    ax_ts.legend(fontsize=7)
    ax_ts.grid(True, alpha=0.3)
    ax_ts.tick_params(labelsize=7)

    # Spatial bias maps
    era5_mean = era5_m.mean("time", skipna=True)
    bc_mean   = bc_m.mean("time", skipna=True)
    bias_bc   = bc_mean - era5_mean

    if raw_m is not None:
        bias_raw = raw_m.mean("time", skipna=True) - era5_mean
        vabs = float(
            max(
                np.nanpercentile(np.abs(bias_raw.values), 98),
                np.nanpercentile(np.abs(bias_bc.values),  98),
            )
        )
    else:
        bias_raw = None
        vabs = float(np.nanpercentile(np.abs(bias_bc.values), 98))

    proj   = ccrs.PlateCarree()
    extent = [
        float(era5_m.lon.min()) - 0.5, float(era5_m.lon.max()) + 0.5,
        float(era5_m.lat.min()) - 0.5, float(era5_m.lat.max()) + 0.5,
    ]

    def _bias_panel(ax, bias_da, title):
        p = ax.pcolormesh(
            bias_da.lon, bias_da.lat, bias_da.values,
            cmap="RdBu_r", vmin=-vabs, vmax=vabs,
            transform=proj, shading="auto",
        )
        ax.add_feature(cfeature.COASTLINE, linewidth=0.5)
        ax.add_feature(cfeature.BORDERS,   linewidth=0.3)
        ax.set_extent(extent, crs=proj)
        ax.set_title(title, fontsize=8)
        return p

    if bias_raw is not None:
        _bias_panel(ax_bias_raw, bias_raw, "Bias: GCM raw − ERA5")
    else:
        ax_bias_raw.set_visible(False)

    p2 = _bias_panel(ax_bias_bc, bias_bc, "Bias: GCM bc − ERA5")

    pos = ax_cb_space.get_position()
    cax = fig.add_axes([pos.x0, pos.y0 + 0.05, 0.015, pos.height * 0.8])
    fig.colorbar(p2, cax=cax, label=f"Δ {label}", extend="both")

    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    log.info("  → %s", out_path.name)


