def plot_timeseries(dfs: dict, cf_name: str, gcm: str, out_path: Path):
    all_states = list(next(iter(dfs.values())).columns)
    ncols = 6
    nrows = int(np.ceil(len(all_states) / ncols))
    fig, axes = plt.subplots(
        nrows, ncols, figsize=(ncols * 3.5, nrows * 2.5), sharex=True
    )
    axes = axes.flatten()
    for i, state in enumerate(all_states):
        ax = axes[i]
        for ssp, df in dfs.items():
            if state in df.columns:
                ax.plot(
                    df.index, df[state],
                    color=SSP_COLORS.get(ssp, "grey"),
                    lw=1.0, label=ssp,
                )
        ax.set_title(state, fontsize=7)
        ax.tick_params(labelsize=6)
        ax.yaxis.set_major_formatter(mticker.FormatStrFormatter("%.2f"))
        if i == 0:
            ax.legend(fontsize=6)
    for j in range(len(all_states), len(axes)):
        axes[j].set_visible(False)
    fig.suptitle(
        f"{cf_name} annual mean by state — {gcm}\n(computed from hourly CF)",
        fontsize=11, y=1.01,
    )
    fig.tight_layout()
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    log.info("  → %s", out_path.name)


def plot_20y_maps(
    cf_20y: dict,
    cf_name: str,
    gcm: str,
    ssp: str,
    gdf,
    cmap: str,
    vmin: float,
    vmax: float,
    out_path: Path,
):
    proj = ccrs.PlateCarree()
    fig, axes = plt.subplots(
        2, 2, figsize=(12, 9), subplot_kw={"projection": proj}
    )
    axes = axes.flatten()
    p = None
    for ax, ((start, end), da) in zip(axes, cf_20y.items()):
        p = ax.pcolormesh(
            da.lon, da.lat, da.values,
            cmap=cmap, vmin=vmin, vmax=vmax,
            transform=proj, shading="auto",
        )
        gdf.boundary.plot(ax=ax, color="black", linewidth=0.4, transform=proj)
        ax.add_feature(cfeature.COASTLINE, linewidth=0.5)
        ax.set_title(f"{start}–{end}", fontsize=10)
        ax.set_extent(
            [
                gdf.total_bounds[0] - 0.5, gdf.total_bounds[2] + 0.5,
                gdf.total_bounds[1] - 0.5, gdf.total_bounds[3] + 0.5,
            ],
            crs=proj,
        )
        gl = ax.gridlines(
            draw_labels=True, linewidth=0.3, color="grey",
            alpha=0.5, linestyle="--",
        )
        gl.top_labels   = False
        gl.right_labels = False
        gl.xlabel_style = {"size": 7}
        gl.ylabel_style = {"size": 7}

    fig.colorbar(
        p, ax=axes, orientation="vertical",
        fraction=0.02, pad=0.04, shrink=0.8,
    ).set_label(f"{cf_name} (hourly mean)", fontsize=9)
    fig.suptitle(f"{cf_name} 20-year mean — {gcm} {ssp}", fontsize=12)
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    log.info("  → %s", out_path.name)


# ══════════════════════════════════════════════════════════════════════════════
# Per-scenario hourly CF writer + aggregation
# ══════════════════════════════════════════════════════════════════════════════

def process_scenario(
    scenario: str,
    hourly_dir: Path,
    out_dir: Path,
    gcm: str,
    run: str,
    gdf,
    region_mask,
    region_col: str,
    periods: list,
    is_ssp: bool,
) -> tuple[pd.DataFrame | None, pd.DataFrame | None]:
    """
    Load hourly file for *scenario*, compute hourly wCF and sCF, write NC
    outputs, aggregate to annual-mean per state, and produce map plots for
    SSP scenarios.

    Returns (df_wind_annual, df_solar_annual) or (None, None) on failure.
    """
    log.info("━━━ %s ━━━", scenario)

    try:
        ds_h = load_hourly(hourly_dir, gcm, scenario)
    except FileNotFoundError as exc:
        log.error("  %s — skipping", exc)
        return None, None

    lat_arr = ds_h["lat"].values
    lon_arr = ds_h["lon"].values
    n_lat   = len(lat_arr)
    n_lon   = len(lon_arr)

    # ── Compute CF (lazy) ─────────────────────────────────────────────────────
    wCF, sCF = compute_cf_from_hourly_ds(ds_h)

    # ── Write hourly CF NetCDFs ───────────────────────────────────────────────
    for cf_da, name in [(wCF, "wCF"), (sCF, "sCF")]:
        out_nc = out_dir / f"{name}_{gcm}_{scenario}_hourly.nc"
        if out_nc.exists():
            log.info("  %s already exists — skipping write", out_nc.name)
        else:
            log.info("  Writing %s …", out_nc.name)
            enc = {
                name: {**ENCODING_HOURLY,
                       "chunksizes": (24, n_lat, n_lon)}
            }
            cf_da.to_netcdf(out_nc, encoding=enc)
            log.info("  → %s", out_nc.name)

    # ── Regional annual aggregation ───────────────────────────────────────────
    log.info("  Aggregating by region …")
    # Load into memory in yearly chunks to keep peak RAM manageable
    df_w_parts, df_s_parts = [], []
    time_idx = pd.DatetimeIndex(ds_h.time.values)
    years    = sorted(set(time_idx.year))

    for yr in years:
        t_slice = slice(f"{yr}-01-01", f"{yr}-12-31")
        wCF_yr  = wCF.sel(time=t_slice).load()
        sCF_yr  = sCF.sel(time=t_slice).load()
        df_w_parts.append(
            regional_annual_mean(wCF_yr, region_mask, gdf, region_col)
        )
        df_s_parts.append(
            regional_annual_mean(sCF_yr, region_mask, gdf, region_col)
        )
        del wCF_yr, sCF_yr

    df_w = pd.concat(df_w_parts)
    df_s = pd.concat(df_s_parts)
    df_w.to_csv(out_dir / f"wCF_{gcm}_{scenario}_states_annual.csv")
    df_s.to_csv(out_dir / f"sCF_{gcm}_{scenario}_states_annual.csv")

    # ── 20-year maps (SSP scenarios only) ────────────────────────────────────
    if is_ssp:
        log.info("  20-year maps …")
        for cf_da, name, cmap, (vmin, vmax) in [
            (wCF, "wCF", "Blues",   (0.0, 0.50)),
            (sCF, "sCF", "Oranges", (0.0, 0.25)),
        ]:
            cf_20y = {}
            for s, e in periods:
                da_period = cf_da.sel(time=slice(str(s), str(e)))
                # annual mean then period mean  (avoids storing all hourly at once)
                da_ann = da_period.resample(time="YE").mean(skipna=True).mean("time", skipna=True)
                cf_20y[(s, e)] = da_ann.load()
            plot_20y_maps(
                cf_20y, name, gcm, scenario, gdf, cmap, vmin, vmax,
                out_dir / f"map_{name}_{gcm}_{scenario}.png",
            )
            del cf_20y

    ds_h.close()
    return df_w, df_s


