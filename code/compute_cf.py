# ══════════════════════════════════════════════════════════════════════════════
# Hourly diurnal validation (solar CF)
# ══════════════════════════════════════════════════════════════════════════════

def plot_diurnal_validation(
    hourly_dir: Path,
    gcm: str,
    train_start: str,
    train_end: str,
    out_path: Path,
):
    """
    Compare the mean diurnal solar CF cycle of the historical hourly BC file
    versus direct ERA5-hourly-derived sCF (if available) on the training
    period.  Plots domain-mean sCF by UTC hour for each calendar month.
    """
    hist_path = hourly_nc_path(hourly_dir, gcm, "historical")
    if not hist_path.exists():
        log.warning(
            "Hourly historical file not found (%s) — skipping diurnal validation", hist_path
        )
        return

    log.info("  Building diurnal solar CF validation …")
    ds_hist = load_hourly(hourly_dir, gcm, "historical").sel(
        time=slice(train_start, train_end)
    )
    _, sCF_hist = compute_cf_from_hourly_ds(ds_hist)

    # domain-mean, group by (month, hour-of-day)
    sCF_dm = sCF_hist.mean(["lat", "lon"], skipna=True).load()
    months_idx = sCF_dm.time.dt.month.values
    hours_idx  = sCF_dm.time.dt.hour.values
    vals       = sCF_dm.values

    fig, axes = plt.subplots(3, 4, figsize=(14, 9), sharey=True, sharex=True)
    axes_flat = axes.flatten()
    month_names = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                   "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

    for m_idx, mname in enumerate(month_names, start=1):
        ax = axes_flat[m_idx - 1]
        mask = months_idx == m_idx
        if mask.any():
            df = pd.DataFrame({"hour": hours_idx[mask], "sCF": vals[mask]})
            mean_diurnal = df.groupby("hour")["sCF"].mean()
            std_diurnal  = df.groupby("hour")["sCF"].std()
            ax.plot(mean_diurnal.index, mean_diurnal.values,
                    color="steelblue", lw=1.5, label="BC hist")
            ax.fill_between(
                mean_diurnal.index,
                mean_diurnal.values - std_diurnal.values,
                mean_diurnal.values + std_diurnal.values,
                alpha=0.25, color="steelblue",
            )
        ax.set_title(mname, fontsize=9)
        ax.set_xlim(0, 23)
        ax.grid(True, alpha=0.3)
        ax.tick_params(labelsize=7)
        if m_idx in {1, 5, 9}:
            ax.set_ylabel("Solar CF", fontsize=8)
        if m_idx >= 9:
            ax.set_xlabel("UTC hour", fontsize=8)

    fig.suptitle(
        f"Mean diurnal solar CF cycle — {gcm} historical BC hourly\n"
        f"({train_start} – {train_end}, domain average ± 1 std)",
        fontsize=11,
    )
    fig.tight_layout()
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    log.info("  → %s", out_path.name)


# ══════════════════════════════════════════════════════════════════════════════
