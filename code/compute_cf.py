def parse_args():
    p = argparse.ArgumentParser(
        description=(
            "Hourly CF computation, regional aggregation, and plots "
            "from downscaled BC GCM data."
        )
    )
    p.add_argument("--bc-dir",      required=True,  type=Path,
                   help="Directory with daily BC NetCDF files (validation only)")
    p.add_argument("--hourly-dir",  required=True,  type=Path,
                   help="Directory with hourly downscaled NetCDF files "
                        "(produced by downscale_hourly.py)")
    p.add_argument("--cmip-dir",    required=True,  type=Path,
                   help="Raw CMIP6 directory (for raw historical comparison in validation)")
    p.add_argument("--shapefile",   required=True,  type=Path,
                   help="GeoJSON / shapefile of Indian states")
    p.add_argument("--out-dir",     required=True,  type=Path,
                   help="Output directory for all products")
    p.add_argument("--gcm",         default="CanESM5")
    p.add_argument("--run",         default="r10i1p1f1")
    p.add_argument("--ssps",        nargs="+", default=["ssp245", "ssp585"])
    p.add_argument("--train-start", default="1980-01-01")
    p.add_argument("--train-end",   default="2010-12-31")
    p.add_argument("--region-col",  default="STNAME_SH")
